#!/usr/bin/env python3
"""Regenerate src/locale_alias.rs from the running Python's locale.locale_alias.

detect_language() reproduces locale.getlocale(), whose normalization is driven
by this table. Run with the python3 the original Linexin Center runs under.
"""
import locale
import pathlib
import sys


def rust_str(value: str) -> str:
    escaped = "".join(
        "\\" + char if char in '\\"' else char if char.isprintable() else f"\\u{{{ord(char):x}}}"
        for char in value
    )
    return f'"{escaped}"'


def main() -> None:
    target = pathlib.Path(__file__).resolve().parent.parent / "src" / "locale_alias.rs"
    # Code point order equals the UTF-8 byte order Rust's binary search uses.
    entries = sorted(locale.locale_alias.items())
    version = ".".join(map(str, sys.version_info[:3]))
    lines = [
        f"// @generated by tools/gen_locale_alias.py from Python {version}'s",
        "// `locale.locale_alias`. Do not edit by hand.",
        "",
        "/// `(alias, locale)` pairs sorted by alias for binary search.",
        "pub(crate) static LOCALE_ALIAS: &[(&str, &str)] = &[",
    ]
    lines += [f"    ({rust_str(key)}, {rust_str(value)})," for key, value in entries]
    lines += ["];", ""]
    target.write_text("\n".join(lines))
    print(f"wrote {len(entries)} entries to {target}")


if __name__ == "__main__":
    main()
